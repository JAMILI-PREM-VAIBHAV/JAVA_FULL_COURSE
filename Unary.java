import java.io.*;
import java.util.*;
class Unary{
    public static void main(String args[]){
        Scanner sc=new Scanner(System.in);
        System.out.println("Enter num: ");
        int num=sc.nextInt();
        // Pre Increment System.out.println(++num);
        // Post Increment System.out.println(num++);
        // Pre Increment System.out.println(--num);
        // Post Decrement System.out.println(num--);
    }
}