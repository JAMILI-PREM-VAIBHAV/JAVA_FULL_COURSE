//Primitive DataTypes
class DataType{
    public static void main(String args[]){
        //Integer
        byte num=1;
        short num1=10;
        int num2=100;
        long l=200l;
        //Float
        float f1=10.203f;
        double f2=10.200000;
        //char
        char ch='P';
        //boolean
        boolean val=true;
    }
}